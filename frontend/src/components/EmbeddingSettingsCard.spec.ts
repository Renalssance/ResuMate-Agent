import { mount, flushPromises } from '@vue/test-utils'
import { beforeEach, expect, it, vi } from 'vitest'
import EmbeddingSettingsCard from './EmbeddingSettingsCard.vue'
const request = vi.hoisted(() => ({ get: vi.fn(), put: vi.fn(), post: vi.fn() }))
vi.mock('../services/request', () => ({ request }))
const saved = { provider: 'qwen', model: 'embed-model', base_url: 'https://embed.example/v1', api_key: 'saved-embed-key', has_api_key: true, api_key_hint: '1234', source: 'saved' }
beforeEach(() => {
 vi.resetAllMocks()
 request.get.mockResolvedValue(saved)
 request.put.mockImplementation((_path, payload) => Promise.resolve({ ...saved, ...payload }))
 request.post.mockResolvedValue({ success: true, dimensions: 1024 })
})
it('shows the saved key and replaces edit with save without adding fields', async () => {
 const w = mount(EmbeddingSettingsCard); await flushPromises()
 const fields = w.findAll('input').length
 expect(w.get<HTMLInputElement>('#embedding-key').element.value).toBe('saved-embed-key')
 expect(w.get('#embedding-key').attributes('readonly')).toBeDefined()
 expect(w.find('input[type=checkbox]').exists()).toBe(false)
 await w.get('[data-edit-embedding]').trigger('click')
 expect(w.get('#embedding-key').attributes('readonly')).toBeUndefined()
 expect(w.get('button[type=submit]').text()).toBe('保存')
 expect(w.findAll('input').length + w.findAll('select').length).toBe(fields)
 await w.get('#embedding-model').setValue('new-model')
 await w.get('#embedding-key').setValue('new-key')
 await w.get('form').trigger('submit'); await flushPromises()
 expect(request.put).toHaveBeenCalledWith('/settings/embedding', expect.objectContaining({ model: 'new-model', api_key: 'new-key' }))
 expect(w.get<HTMLInputElement>('#embedding-key').element.value).toBe('new-key')
 expect(w.get('#embedding-key').attributes('readonly')).toBeDefined()
 w.unmount()
})
it('tests saved configuration even when unsaved fields are being edited', async () => {
 const w = mount(EmbeddingSettingsCard); await flushPromises()
 await w.get('[data-edit-embedding]').trigger('click')
 await w.get('#embedding-model').setValue('unsaved')
 await w.get('[data-test-connection]').trigger('click'); await flushPromises()
 expect(request.post).toHaveBeenCalledWith('/settings/embedding/test')
 expect(w.text()).toContain('1024')
 request.post.mockRejectedValue(new Error('连接测试失败'))
 await w.get('[data-test-connection]').trigger('click'); await flushPromises()
 expect(w.get('[role=alert]').text()).toContain('连接测试失败')
 w.unmount()
})
it('retains edits on save failure and restores saved values with Escape', async () => {
 const w = mount(EmbeddingSettingsCard); await flushPromises()
 await w.get('[data-edit-embedding]').trigger('click')
 await w.get('#embedding-model').setValue('unsaved')
 request.put.mockRejectedValue(new Error('保存失败'))
 await w.get('form').trigger('submit'); await flushPromises()
 expect(w.get<HTMLInputElement>('#embedding-model').element.value).toBe('unsaved')
 expect(w.get('[role=alert]').text()).toBe('保存失败')
 await w.get('form').trigger('keydown', { key: 'Escape' })
 expect(w.get<HTMLInputElement>('#embedding-model').element.value).toBe('embed-model')
 expect(w.get('#embedding-model').attributes('readonly')).toBeDefined()
 w.unmount()
})
