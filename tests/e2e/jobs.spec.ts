import { test, expect, snapshot, waitForRun } from './support/fixtures'
import type { Page } from '@playwright/test'

const jobText = '负责 API 和数据库设计，需要结合真实经历说明项目职责。'.repeat(16)
async function capture(page: Page, name: string, mobile = false, fullPage = false) {
  await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 1100 })
  if (mobile) {
    const open = page.getByRole('button', { name: '打开导航', exact: true })
    await expect(open).toBeVisible()
    if (await open.getAttribute('aria-expanded') === 'true') await page.getByRole('button', { name: '关闭导航', exact: true }).click()
    await expect(page.getByRole('dialog', { name: '主导航', exact: true })).toBeHidden()
  }
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  if (name.startsWith('facts-')) {
    await page.getByRole('region', { name: '确认事实', exact: true }).screenshot({ path: test.info().outputPath(`${name}.png`), animations: 'disabled' })
  } else {
    await page.screenshot({ path: test.info().outputPath(`${name}.png`), fullPage: mobile || fullPage, animations: 'disabled' })
  }
}

// Every business response below comes from the actual API and SQL. Only the
// external model HTTP transport is replaced in the test API entrypoint.
test('岗位收藏解析关联后进入材料准备并由独立 worker 完成', async ({ page, api }) => {
  await page.goto('/jobs')
  await page.getByLabel('岗位名称', { exact: true }).fill('平台 API 工程师')
  await page.getByLabel('公司', { exact: true }).fill('示例科技团队')
  await page.getByLabel('岗位原文', { exact: true }).fill(jobText)
  await page.getByLabel('来源链接', { exact: true }).fill('https://example.com/jobs/backend')
  const saved = page.waitForResponse(r => r.url().endsWith('/api/jobs') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '收藏岗位', exact: true }).click()
  const response = await saved
  expect(response.ok()).toBe(true)
  const { job, created } = await response.json()
  expect(created).toBe(true)
  const detail = page.getByRole('region', { name: '岗位详情', exact: true })
  await expect(detail).toBeVisible()
  await capture(page, 'jobs-long-desktop', false, true)
  await capture(page, 'jobs-long-mobile', true)
  await page.setViewportSize({ width: 1440, height: 1100 })
  await detail.getByLabel('主简历', { exact: true }).selectOption('1')
  await detail.getByRole('button', { name: '保存岗位', exact: true }).click()
  await expect.poll(async () => (await (await api.get(`/api/jobs/${job.id}`)).json()).primaryResumeId).toBe(1)
  await detail.getByRole('button', { name: '解析岗位', exact: true }).click()
  await expect.poll(async () => (await (await api.get(`/api/jobs/${job.id}`)).json()).parseStatus).toBe('success')
  await detail.getByRole('link', { name: '去匹配', exact: true }).click()
  await expect(page).toHaveURL(/\/matching\?/)
  await expect(page.getByRole('combobox', { name: '目标 JD', exact: true })).toHaveValue(`jd:${job.id}`)
  await expect(page.getByRole('listbox', { name: '候选人简历', exact: true })).toHaveValues(['resume:1'])
  await page.goto('/jobs')
  await page.locator(`[data-job-id="${job.id}"]`).click()
  await page.getByRole('region', { name: '岗位详情', exact: true }).getByRole('link', { name: '准备材料', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '目标岗位', exact: true })).toHaveValue(`jd:${job.id}`)
  await expect(page.getByRole('combobox', { name: '主简历', exact: true })).toHaveValue('resume:1')
  await page.getByRole('button', { name: '开始准备', exact: true }).click()
  await expect(page).toHaveURL(/\/agent\/tasks\/[^/?]+$/)
  const runId = page.url().split('/').pop()!
  await page.getByLabel('你负责什么工作？', { exact: true }).fill('负责 API 和数据库设计。')
  await page.getByRole('button', { name: '继续任务', exact: true }).click()
  await expect(page.getByRole('heading', { name: '材料已生成', exact: true })).toBeVisible()
  expect((await waitForRun(api, runId, 'succeeded')).outputRefs).toHaveLength(1)
  expect((await snapshot(api, runId)).cancelRequested).toBe(false)
})

test('用户确认经历后编辑保留历史，删除后可追溯', async ({ page, api }) => {
  await page.goto('/profile-fields')
  await page.getByRole('combobox', { name: '选择简历', exact: true }).selectOption('resume:1')
  const facts = page.getByRole('region', { name: '确认事实', exact: true })
  await expect(facts).toBeVisible()
  await facts.getByLabel('从简历选择经历', { exact: true }).selectOption('work_experience:0')
  await expect(facts.getByLabel('我已核对，确认这条事实', { exact: true })).not.toBeChecked()
  await facts.getByLabel('事实内容', { exact: true }).fill('负责 API 和数据库设计，并与团队核对接口需求。'.repeat(8))
  await facts.getByLabel('我已核对，确认这条事实', { exact: true }).check()
  const saved = page.waitForResponse(r => r.url().endsWith('/api/profile-facts') && r.request().method() === 'POST')
  await facts.getByRole('button', { name: '保存事实', exact: true }).click()
  const initial = await (await saved).json()
  expect(initial.revision).toBe(1)
  expect(initial.sourceDocumentId).toBe(1)
  expect(initial.confirmedAt).toBeTruthy()
  await capture(page, 'facts-confirmed-desktop')
  await capture(page, 'facts-confirmed-mobile', true)
  await facts.getByRole('button', { name: '编辑事实', exact: true }).first().click()
  await facts.getByLabel('事实内容', { exact: true }).fill('负责 API 设计、数据库模型与接口联调。')
  const updated = page.waitForResponse(r => r.url().includes('/api/profile-facts/') && r.request().method() === 'PATCH')
  await facts.getByRole('button', { name: '保存修改', exact: true }).click()
  const second = await (await updated).json()
  expect(second.revision).toBe(2)
  expect(second.confirmedAt).toBeNull()
  await facts.getByRole('button', { name: '查看历史', exact: true }).first().click()
  const history = await (await api.get(`/api/profile-facts/${second.id}/history`)).json()
  expect(history.items.map((item: { revision: number }) => item.revision)).toEqual([1, 2])
  await capture(page, 'facts-history-mobile', true)
  const removed = page.waitForResponse(r => r.url().includes('/api/profile-facts/') && r.request().method() === 'DELETE')
  await facts.getByRole('button', { name: '删除事实', exact: true }).first().click()
  const tombstone = await (await removed).json()
  expect(tombstone.revision).toBe(3)
  expect(tombstone.deletedAt).toBeTruthy()
  await facts.getByLabel('显示已删除事实', { exact: true }).check()
  await expect(facts.getByText('已删除', { exact: true }).first()).toBeVisible()
})

test('岗位解析错误保留原文可重试，筛选无结果有空状态', async ({ page, api }) => {
  const created = await api.post('/api/jobs', { data: { title: '解析重试示例', text: 'E2E_RETRY_PARSE 负责 API 和数据库设计。' } })
  const { job } = await created.json()
  await page.goto('/jobs')
  await page.locator(`[data-job-id="${job.id}"]`).click()
  const detail = page.getByRole('region', { name: '岗位详情', exact: true })
  await detail.getByRole('button', { name: '解析岗位', exact: true }).click()
  await expect(detail.getByRole('button', { name: '重试解析', exact: true })).toBeVisible()
  expect((await (await api.get(`/api/jobs/${job.id}`)).json()).text).toContain('E2E_RETRY_PARSE')
  await capture(page, 'jobs-parse-error-mobile', true)
  await detail.getByRole('button', { name: '重试解析', exact: true }).click()
  await expect.poll(async () => (await (await api.get(`/api/jobs/${job.id}`)).json()).parseStatus).toBe('success')
  await page.getByLabel('搜索岗位', { exact: true }).fill('没有匹配的岗位名称')
  await page.getByLabel('搜索岗位', { exact: true }).press('Enter')
  await expect(page.getByText('没有符合筛选条件的岗位。试试其他关键词或状态。', { exact: true })).toBeVisible()
  await capture(page, 'jobs-filter-empty-desktop')
})
